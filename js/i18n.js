const STRINGS = {en, pl, de, fr, es};

let current = 'en';

/** Saved choice, then the browser's languages, then English. */
export function detectLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && STRINGS[saved]) return saved;
  } catch {
    // storage blocked; fall through to the browser setting
  }
  for (const tag of navigator.languages || [navigator.language || '']) {
    const id = String(tag).slice(0, 2).toLowerCase();
    if (STRINGS[id]) return id;
  }
  return 'en';
}

export function language() {
  return current;
}

export function setLanguage(id) {
  current = STRINGS[id] ? id : 'en';
  document.documentElement.lang = current;
  try {
    localStorage.setItem(STORAGE_KEY, current);
  } catch {
    // not fatal: the choice simply will not be remembered
  }
  return current;
}

export function locale() {
  return LANGUAGES.find((l) => l.id === current)?.locale || 'en-GB';
}

function fill(template, params) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, k) => (k in params ? String(params[k]) : `{${k}}`));
}

/** Translation for a key, falling back to English and then to the key itself. */
export function t(key, params) {
  const table = STRINGS[current] || en;
  return fill(table[key] ?? en[key] ?? key, params);
}

/** Translation for a name defined in the data, falling back to its English label. */
export function tf(key, fallback) {
  const table = STRINGS[current] || en;
  return table[key] ?? fallback ?? en[key] ?? key;
}

export function formatNumber(n) {
  return Number(n).toLocaleString(locale());
}

/**
 * Applies every translation marked up in the DOM. Run once at start and again
 * after the language changes.
 */
export function applyTranslations(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-ph]')) node.placeholder = t(node.dataset.i18nPh);
  for (const node of root.querySelectorAll('[data-i18n-title]')) {
    const value = t(node.dataset.i18nTitle);
    node.title = value;
    if (node.hasAttribute('aria-label')) node.setAttribute('aria-label', value);
  }
  // The data credit keeps its link markup, so it is filled in by hand.
  const credit = root.querySelector('#foot-data');
  if (credit) {
    credit.innerHTML = t('foot.data', {
      ne: '<a href="https://www.naturalearthdata.com/" target="_blank" rel="noopener">Natural Earth</a>',
      d3: '<a href="https://d3js.org/" target="_blank" rel="noopener">d3-geo</a>',
    });
  }
}
